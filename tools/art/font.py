STYLES = {
    # name: (text rgb, shadow rgb)
    'white': ((246, 246, 250), (28, 30, 48)),
    'dark':  ((40, 42, 60), (196, 200, 214)),
    'gold':  ((255, 214, 92), (74, 46, 12)),
    'red':   ((255, 110, 104), (68, 20, 24)),
    'green': ((124, 234, 140), (18, 60, 30)),
    'blue':  ((120, 200, 255), (14, 40, 76)),
    'pink':  ((255, 140, 196), (70, 18, 46)),
    'gray':  ((150, 156, 180), (28, 30, 48)),
    'ink':   ((40, 42, 60), None),   # no shadow — for light paper panels
}


def build_face(glyphs, name, rows_above_baseline, line_height, space_w, out_dir):
    chars = [c for c in glyphs]
    chars.sort(key=ord)
    cell_h = max(len(r) for r in glyphs.values()) + 1
    cell_h = max(cell_h, rows_above_baseline + 3)
    pad = 2
    cols = 16
    widths = {c: max(len(row) for row in glyphs[c]) for c in chars}
    cell_w = max(widths.values()) + 1 + pad
    nrows = (len(chars) + cols - 1) // cols
    W, H = cols * cell_w, nrows * (cell_h + pad)
    for style, (fg, sh) in STYLES.items():
        img = Image.new('RGBA', (W, H), (0, 0, 0, 0))
        px = img.load()
        entries = []
        for i, c in enumerate(chars):
            cx, cy = (i % cols) * cell_w, (i // cols) * (cell_h + pad)
            rows = glyphs[c]
            w = widths[c]
            on = set()
            for y, row in enumerate(rows):
                for x, ch in enumerate(row):
                    if ch == '#':
                        on.add((x, y))
            if sh:
                for (x, y) in on:
                    if (x + 1, y + 1) not in on:
                        px[cx + x + 1, cy + y + 1] = sh + (255,)
            for (x, y) in on:
                px[cx + x, cy + y] = fg + (255,)
            gw = w + (1 if sh else 0)
            gh = len(rows) + (1 if sh else 0)
            entries.append((ord(c), cx, cy, gw, gh, 0, 0, w + 1))
        # space
        entries.append((32, 0, 0, 0, 0, 0, 0, space_w))
        fname = f'{name}_{style}'
        img.save(os.path.join(out_dir, fname + '.png'))
        with open(os.path.join(out_dir, fname + '.xml'), 'w') as f:
            f.write('<?xml version="1.0"?>\n<font>\n')
            f.write(f'  <info face="{fname}" size="{rows_above_baseline}" bold="0" italic="0" charset="" unicode="1" stretchH="100" smooth="0" aa="0" padding="0,0,0,0" spacing="0,0"/>\n')
            f.write(f'  <common lineHeight="{line_height}" base="{rows_above_baseline}" scaleW="{W}" scaleH="{H}" pages="1" packed="0"/>\n')
            f.write(f'  <pages><page id="0" file="{fname}.png"/></pages>\n')
            f.write(f'  <chars count="{len(entries)}">\n')
            for (cid, x, y, w, h, xo, yo, xa) in entries:
                f.write(f'    <char id="{cid}" x="{x}" y="{y}" width="{w}" height="{h}" xoffset="{xo}" yoffset="{yo}" xadvance="{xa}" page="0" chnl="15"/>\n')
            f.write('  </chars>\n</font>\n')


def build(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    build_face(MAIN, 'main', 7, 12, 3, out_dir)
    build_face(SMALL, 'small', 5, 7, 2, out_dir)


if __name__ == '__main__':
    build('public/assets/fonts')
